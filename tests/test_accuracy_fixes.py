"""Regression tests for the two problems the accuracy evaluation found.

1. A photo that gets brightened or captioned must still be matched (the photo/document
   guess used to flip, which skipped visual matching).
2. Innocent metadata that merely contains a marker word ("Gemini Studios") must not be
   flagged, while real AI tool names still are.
"""

import io

import pytest
from PIL import Image, ImageDraw, ImageEnhance
from PIL.PngImagePlugin import PngInfo

from app.pipeline import fingerprint as fp
from app.pipeline.provenance import check_provenance
from tests.test_check import codes, run


def _jpeg(im, q=90, **kw):
    buf = io.BytesIO()
    im.convert("RGB").save(buf, "JPEG", quality=q, **kw)
    return buf.getvalue()


def _brightened(data, f=1.3):
    return _jpeg(ImageEnhance.Brightness(Image.open(io.BytesIO(data)).convert("RGB")).enhance(f))


def _captioned(data):
    im = Image.open(io.BytesIO(data)).convert("RGB")
    d = ImageDraw.Draw(im)
    d.rectangle((0, im.height - im.height // 12, im.width, im.height), fill=(0, 0, 0))
    return _jpeg(im)


# ------------------------------------------------------------------ 1. classification
def test_classification_still_separates_photo_and_paper(sample):
    assert fp.classify(sample("photo1.jpg")) == "photo"
    assert fp.classify(sample("marksheet1.png")) == "document"


@pytest.mark.parametrize("edit", [_brightened, _captioned])
def test_edited_photo_is_still_matched(db, sample, edit):
    run(db, sample("photo1.jpg"), "APP-1", "citizen-1")
    r = run(db, edit(sample("photo1.jpg")), "APP-2", "citizen-2")
    assert r.level == "high" and "DUPLICATE_PHOTO" in codes(r)


def test_document_is_not_matched_to_other_documents(db, sample):
    """Same printed layout, different people: still only exact copies match."""
    run(db, sample("marksheet1.png"), "APP-1", "citizen-1", name="m1.png")
    r = run(db, sample("marksheet2.png"), "APP-2", "citizen-2", name="m2.png")
    assert r.level == "none"


def test_explicit_document_type_skips_visual_matching(db, sample):
    run(db, sample("photo1.jpg"), "APP-1", "citizen-1")
    r = run(db, _brightened(sample("photo1.jpg")), "APP-2", "citizen-2", doc_type="document")
    assert r.level == "none"


# ------------------------------------------------------------------ 2. markers
def _exif_jpeg(**tags):
    ids = {"Software": 0x0131, "Artist": 0x013B, "ImageDescription": 0x010E}
    im = Image.new("RGB", (64, 64), (120, 90, 60))
    ex = im.getexif()
    for k, v in tags.items():
        ex[ids[k]] = v
    return _jpeg(im, exif=ex)


def _hints(data, mime="image/jpeg"):
    return check_provenance(data, mime)[0].ai_hints


@pytest.mark.parametrize(
    "tags",
    [
        {"Software": "Midjourney v6.1"},
        {"Software": "Google Gemini"},
        {"Software": "Imagen 3"},
        {"Software": "Runway ML"},
        {"Software": "DALL·E 3"},
        {"Software": "DALL-E 2"},
        {"Software": "OpenAI"},
        {"Artist": "Midjourney"},
        {"ImageDescription": "Image made with DALL-E 3"},
        {"ImageDescription": "Generated by Gemini"},
    ],
)
def test_real_ai_names_are_flagged(tags):
    assert _hints(_exif_jpeg(**tags)), tags


@pytest.mark.parametrize(
    "tags",
    [
        {"Artist": "Gemini Photo Studio"},
        {"Artist": "Dalle Nogare"},
        {"ImageDescription": "Visit to the OpenAI office, Mumbai"},
        {"ImageDescription": "Photo of the Gemini constellation"},
        {"ImageDescription": "ideogram of the character for tree"},
        {"Software": "Samsung SM-S918B"},
        {"Software": "Microsoft Photos"},
        {"Software": "Adobe Lightroom Mobile"},
    ],
)
def test_innocent_metadata_is_not_flagged(tags):
    assert not _hints(_exif_jpeg(**tags)), tags


def _png(**text):
    info = PngInfo()
    for k, v in text.items():
        info.add_text(k, v)
    buf = io.BytesIO()
    Image.new("RGB", (64, 64)).save(buf, "PNG", pnginfo=info)
    return buf.getvalue()


def test_png_generic_keys_need_ai_looking_content():
    assert not _hints(_png(prompt="Please enter your name"), "image/png")
    assert not _hints(_png(parameters="hello"), "image/png")
    assert _hints(_png(prompt='{"3": {"class_type": "KSampler"}}'), "image/png")
    assert _hints(_png(parameters="a cat\nSteps: 20, Sampler: Euler a, Seed: 5"), "image/png")
    assert _hints(_png(invokeai_metadata="{}"), "image/png")


def test_xmp_creator_tool_is_a_tool_field():
    xmp = (b'<x:xmpmeta xmlns:x="adobe:ns:meta/"><rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">'
           b'<rdf:Description xmlns:xmp="http://ns.adobe.com/xap/1.0/"><xmp:CreatorTool>Imagen 3</xmp:CreatorTool>'
           b"</rdf:Description></rdf:RDF></x:xmpmeta>")  # fmt: skip
    buf = io.BytesIO()
    Image.new("RGB", (64, 64)).save(buf, "JPEG", xmp=xmp)
    assert _hints(buf.getvalue())
