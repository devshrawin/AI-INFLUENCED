#!/usr/bin/env python3
"""Calibrate the Binoculars threshold for the installed model pair.

Usage:
    python eval/calibrate_binoculars.py <folder with real/ and ai/ .txt files>

Prints the raw Binoculars scores for both classes and suggests:
  BINOCULARS_THRESHOLD  (score at which P(AI) = 50%; best balanced accuracy)
  BINOCULARS_SCALE      (spread used for the probability curve)
Put the suggested values in .env. Use local, representative documents
(e.g. officer-written notes vs. text generated by common chatbots).
"""

from __future__ import annotations

import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.config import get_settings  # noqa: E402
from app.pipeline.detectors.text import Binoculars  # noqa: E402


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    root = Path(sys.argv[1])
    s = get_settings()
    det = Binoculars(s.models_dir, s.binoculars_observer, s.binoculars_performer, s.device)
    det.ensure_loaded()
    scores: dict[str, list[float]] = {"real": [], "ai": []}
    for label in scores:
        for path in sorted((root / label).glob("*.txt")):
            score, _ = det.raw_score(path.read_text(encoding="utf-8"))
            scores[label].append(score)
            print(f"{label:4s} {score:.4f} {path.name}", flush=True)

    real, ai = scores["real"], scores["ai"]
    best_t, best_acc = 0.0, 0.0
    for t in sorted(real + ai):
        acc = (sum(x >= t for x in real) / len(real) + sum(x < t for x in ai) / len(ai)) / 2
        if acc > best_acc:
            best_t, best_acc = t, acc
    # Threshold keeping false positives (human flagged as AI) at or below 5%.
    low_fpr_t = sorted(real)[max(0, int(len(real) * 0.05) - 1)] if real else best_t
    spread = (statistics.pstdev(real) + statistics.pstdev(ai)) / 2
    print(f"\nreal: mean {statistics.mean(real):.4f}  ai: mean {statistics.mean(ai):.4f}")
    print(f"Best balanced accuracy {best_acc:.3f} at threshold {best_t:.4f}")
    print(f"Threshold for ~5% false-positive rate: {low_fpr_t:.4f}")
    print(f"Suggested .env:\nBINOCULARS_THRESHOLD={best_t:.4f}\nBINOCULARS_SCALE={max(spread / 2, 0.01):.4f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
